function tierFor(city) {
  if (TIER_1.has(city)) return '一线城市';
  if (NEW_TIER_1.has(city)) return '新一线';
  if (OVERSEAS_OR_MULTI.has(city)) return '其他/海外';
  return '省会及重点城市';
}

